"""
Educational demonstration script that analyzes sample project data and generates
a concise summary. If an OpenAI API key is available, the script uses the API.
Otherwise, it generates the summary locally.
"""

import json
import os
import statistics
from dataclasses import dataclass
from typing import List


@dataclass
class Task:
    name: str
    planned_days: int
    actual_days: int
    cost_egp: float


sample_tasks: List[Task] = [
    Task("Topographic Site Survey", 3, 4, 42000),
    Task("Conceptual Design Development", 7, 9, 120000),
    Task("Structural Load Calculations", 10, 12, 180000),
    Task("Preparing AutoCAD Drawings", 6, 5, 75000),
    Task("Project Approval with Client", 4, 6, 30000),
    Task("Cost Estimation Documentation", 5, 5, 45000),
    Task("Construction Site Supervision", 8, 10, 100000),
]


def tasks_to_table_text(tasks: List[Task]) -> str:
    header = f"{'Task':40s} | Planned | Actual | Cost (EGP)"
    lines = [header, "-" * len(header)]

    for task in tasks:
        lines.append(
            f"{task.name:40s} | "
            f"{task.planned_days:7d} | "
            f"{task.actual_days:6d} | "
            f"{task.cost_egp:10.2f}"
        )

    return "\n".join(lines)


def offline_summary(tasks: List[Task]) -> str:
    total_planned = sum(t.planned_days for t in tasks)
    total_actual = sum(t.actual_days for t in tasks)
    total_cost = sum(t.cost_egp for t in tasks)

    delay = total_actual - total_planned
    delay_percent = (delay / total_planned * 100) if total_planned else 0

    delayed_tasks = [t for t in tasks if t.actual_days > t.planned_days]
    early_tasks = [t for t in tasks if t.actual_days < t.planned_days]

    worst_task = max(tasks, key=lambda t: t.actual_days - t.planned_days)
    average_cost = statistics.mean(t.cost_egp for t in tasks)

    return "\n".join([
        "PROJECT SUMMARY",
        f"Total tasks: {len(tasks)}",
        f"Total planned duration: {total_planned} days",
        f"Total actual duration: {total_actual} days",
        f"Schedule deviation: {delay:+d} days ({delay_percent:+.1f}%)",
        f"Total project cost: EGP {total_cost:,.2f}",
        f"Average task cost: EGP {average_cost:,.2f}",
        f"Delayed tasks: {len(delayed_tasks)}",
        f"Completed ahead of schedule: {len(early_tasks)}",
        f"Largest delay: {worst_task.name} (+{worst_task.actual_days - worst_task.planned_days} days)",
    ])


def call_llm_api(table_text: str) -> str:
    api_key = os.environ.get("OPENAI_API_KEY")

    if not api_key:
        raise RuntimeError("API key not found.")

    import urllib.request

    prompt = (
        "You are an engineering project assistant. "
        "Review the following project schedule and provide a short summary "
        "in 5-7 bullet points, including schedule deviation, major delays, "
        "and total project cost.\n\n"
        f"{table_text}"
    )

    payload = json.dumps({
        "model": "gpt-4o-mini",
        "messages": [
            {
                "role": "user",
                "content": prompt
            }
        ],
        "max_tokens": 400
    }).encode("utf-8")

    request = urllib.request.Request(
        "https://api.openai.com/v1/chat/completions",
        data=payload,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}"
        }
    )

    with urllib.request.urlopen(request, timeout=20) as response:
        data = json.loads(response.read().decode("utf-8"))

    return data["choices"][0]["message"]["content"]


def main():
    table = tasks_to_table_text(sample_tasks)

    print("=" * 70)
    print("INPUT DATA")
    print("=" * 70)
    print(table)
    print()

    print("=" * 70)
    print("PROJECT ANALYSIS")
    print("=" * 70)

    try:
        summary = call_llm_api(table)
        print("[Summary generated by OpenAI API]\n")
    except Exception as error:
        summary = offline_summary(sample_tasks)
        print(f"[Offline summary used: {error}]\n")

    print(summary)
    print("=" * 70)


if __name__ == "__main__":
    main()